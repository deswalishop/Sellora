const MOBILE_ITEMS = [
  { href: "/overview", label: "Home", icon: "home" },
  { href: "/orders", label: "Orders", icon: "orders" },
  { href: "/products", label: "Products", icon: "products" },
  { href: "/settings", label: "Settings", icon: "settings" },
];

/** Shopify-admin-style nav with active highlighting. */
export function DashNav({ mobile = false }: { mobile?: boolean }) {
  const pathname = usePathname();
  const isActive = (href: string) =>
    href === "/overview" ? pathname === "/overview" : pathname === href || pathname.startsWith(href + "/");

  if (mobile) {
    return (
      <>
        {MOBILE_ITEMS.map((item) => (
          <Link
            key={item.href}
            href={item.href}
            className={`flex flex-1 flex-col items-center gap-1 py-2.5 text-[11px] ${
              isActive(item.href) ? "font-semibold text-neutral-900" : "text-neutral-500"
            }`}
          >
            {ICONS[item.icon]}
            {item.label}
          </Link>
        ))}
      </>
    );
  }

  return (
    <nav className="space-y-5">
      {GROUPS.map((g, gi) => (
        <div key={gi}>
          {g.label && (
            <p className="px-3 pb-1 text-[11px] font-semibold uppercase tracking-wider text-neutral-400">
              {g.label}
            </p>
          )}
          <ul className="space-y-0.5">
            {g.items.map((item) => (
              <li key={item.href}>
                <Link
                  href={item.href}
                  className={`flex items-center gap-3 rounded-lg px-3 py-2 text-sm transition ${
                    isActive(item.href)
                      ? "bg-neutral-100 font-semibold text-neutral-900"
                      : "text-neutral-600 hover:bg-neutral-50 hover:text-neutral-900"
                  }`}
                >
                  <span className={isActive(item.href) ? "text-neutral-900" : "text-neutral-400"}>
                    {ICONS[item.icon]}
                  </span>
                  {item.label}
                </Link>
              </li>
            ))}
          </ul>
        </div>
      ))}
    </nav>
  );
}
